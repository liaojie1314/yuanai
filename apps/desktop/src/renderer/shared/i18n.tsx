function normalizeLocale(locale: string): DesktopLocale {
  return locale === 'en' ? 'en' : DEFAULT_LOCALE
}

/** 桌面端唯一的 i18next 实例，复用 Web 的公共翻译并扩展 Electron 专属文案。 */
export const desktopI18n: I18nInstance = i18n.createInstance()

void desktopI18n.use(initReactI18next).init({
  resources: {
    'zh-CN': { translation: { ...zhCN, ...desktopTranslations['zh-CN'] } },
    en: { translation: { ...desktopEnglishTranslations, ...desktopTranslations.en } },
  },
  lng: DEFAULT_LOCALE,
  fallbackLng: DEFAULT_LOCALE,
  interpolation: { escapeValue: false, prefix: '{', suffix: '}' },
  initImmediate: false,
  react: { useSuspense: false },
})

/** 将指定语言应用到当前 Electron renderer。 */
export async function changeDesktopLanguage(locale: string): Promise<void> {
  await desktopI18n.changeLanguage(normalizeLocale(locale))
}

/** 让当前 renderer 内所有 React 组件使用同一个 i18next 实例。 */
export function DesktopI18nProvider({ children }: { children: ReactNode }): ReactElement {
  return <I18nextProvider i18n={desktopI18n}>{children}</I18nextProvider>
}
